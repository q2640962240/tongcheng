/**
 * 返回「省→市」两级树
 *   provinces: [{ code, name, abbr, spell, firstLetter, cities: City[] }]
 */
function getRegionTree() {
  const byProvince = new Map(DATASET.provinces.map(p => [p.code, { ...p, cities: [] }]))
  for (const c of DATASET.cities) {
    const bucket = byProvince.get(c.provinceCode)
    if (bucket) bucket.cities.push({ ...c })
  }
  const provinces = Array.from(byProvince.values()).sort((a, b) => a.code.localeCompare(b.code))
  for (const p of provinces) p.cities.sort((a, b) => a.code.localeCompare(b.code))
  return { meta: { ...DATASET.meta }, provinces }
}

/**
 * 搜索城市：中文 / 拼音全拼 / 拼音首字母 / 别名 都命中
 * @param {string} kw
 * @returns {Array} 命中列表（按相关性排序）
 */
function searchRegions(raw) {
  const kw = String(raw || '').trim().toLowerCase()
  if (!kw) return []
  const letters = kw.replace(/[^a-zA-Z]/g, '')
  const hasChinese = /[\u4e00-\u9fa5]/.test(kw)
  const isPureLetter = letters.length === kw.length
  const scored = []
  for (const c of DATASET.cities) {
    let score = 0
    const name = c.name
    const nameLow = name.toLowerCase()
    // 1. 中文完全匹配
    if (hasChinese && name === kw) score += 100
    // 2. 中文前缀
    if (hasChinese && name.startsWith(kw)) score += 70
    else if (hasChinese && name.includes(kw)) score += 40
    // 3. 省名直接命中：别名里包含省名的 +60
    if (hasChinese && c.alias.includes(kw)) score += 60
    // 4. 纯字母匹配：完全等于 spell 或等于首字母
    if (isPureLetter && letters) {
      if (c.spell === letters) score += 90
      else if (c.firstLetter && c.firstLetter.startsWith(letters)) score += 75
      else if (c.spell.startsWith(letters)) score += 55
      else if (c.spell.includes(letters)) score += 30
      // alias 里的英文/缩写（bj/sh/gz）
      for (const a of c.alias) {
        const low = String(a).toLowerCase()
        if (!low) continue
        if (low === letters) { score += 80; break }
        if (low.startsWith(letters)) { score += 40; break }
      }
    } else if (letters) {
      // 混合命中：拼英片段
      if (c.spell.includes(letters)) score += 20
    }
    // 5. alias 中文包含
    if (hasChinese) {
      for (const a of c.alias) {
        if (String(a).includes(kw)) { score += 35; break }
      }
    }
    if (!hasChinese && !isPureLetter) {
      // 数字/英文符号场景：不打分
    }
    if (score > 0) scored.push({ score, city: c })
  }
  scored.sort((a, b) => b.score - a.score || a.city.code.localeCompare(b.city.code))
  // 输出统一为带「语义别名」的形态，同时保留原字段兼容旧代码：
  //   spell      -> pinyin（全拼）
  //   firstLetter(首字符大写) -> initial(首字母, 保留)
  //   alias(数组) -> aliases（复数）
  return scored.slice(0, 50).map(x => ({
    ...x.city,
    pinyin: x.city.spell || '',
    initial: x.city.firstLetter || '',
    aliases: Array.isArray(x.city.alias) ? x.city.alias : []
  }))
}

